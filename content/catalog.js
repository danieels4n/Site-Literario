// Faixa de níveis de uma trilha, para exibir (ex.: “Introdutório → Aprofundado”).
export function faixaNivel(trilha) {
  const niveis = trilha.etapas.map((e) => livroPorSlug.get(e.livro).nivel);
  const ini = niveis[0];
  const fim = niveis[niveis.length - 1];
  return ini === fim ? NIVEIS[ini] : `${NIVEIS[ini]} → ${NIVEIS[fim]}`;
}
